const entries = contexts.map(
  ([slug, category, sourceEntryId, date, title, titleUk, evidence, pl, uk]) => {
    const source = history.find((entry) => entry.id === sourceEntryId);
    if (!source?.original.includes(evidence)) {
      throw new Error(`Missing original history evidence: ${slug}`);
    }
    return {
      slug,
      category,
      sourceEntryId,
      date,
      title,
      titleUk,
      evidence,
      pl,
      uk,
      sourceTitle: source.title,
    };
  },
);

function choicesFor(item, field) {
  const candidates = entries.filter(
    (entry) => entry.category === item.category && entry.date !== item.date,
  );
  // Source entries also supply distractors for categories with few added contexts.
  const sourceCandidates = history
    .filter(
      (entry) =>
        entry.category === item.category &&
        entry.id !== item.sourceEntryId &&
        !entry.year.includes(item.date),
    )
    .map((entry) => ({ date: entry.year, title: entry.title }));
  return [
    ...new Set([
      item[field],
      ...candidates.map((entry) => entry[field]),
      ...sourceCandidates.map((entry) => entry[field]),
    ]),
  ].slice(0, 5);
}

export const extraHistoryTranslations = { pl: {} };

export const extraHistoryExercises = entries.flatMap((item) => {
  const familyId = `history-extra-${item.slug}`;
  const shared = {
    familyId,
    topic: 'history',
    historyCategory: item.category,
    sourceEntryId: item.sourceEntryId,
    originalEvidence: item.evidence,
    explanation: item.uk,
  };
  const datePrompt = `Jaka data pasuje do wydarzenia: ${item.title}?`;
  const eventPrompt = `Które wydarzenie z części „${item.sourceTitle}” pasuje do daty „${item.date}”?`;
  const exercises = [
    {
      ...shared,
      id: `${familyId}-year`,
      level: 'choice',
      prompt: datePrompt,
      answers: [item.date],
      options: choicesFor(item, 'date'),
    },
    {
      ...shared,
      id: `${familyId}-write`,
      level: 'write',
      prompt: `Впиши дату: ${item.titleUk}`,
      answers: [...new Set([item.date, item.date.replace(/[–—]/gu, '-')])],
    },
    {
      ...shared,
      id: `${familyId}-event`,
      level: 'event',
      prompt: eventPrompt,
      answers: [item.title],
      options: choicesFor(item, 'title'),
    },
  ];
  for (const exercise of exercises) {
    extraHistoryTranslations.pl[exercise.id] = {
      prompt: exercise.level === 'write' ? `Wpisz datę: ${item.title}` : exercise.prompt,
      explanation: item.pl,
    };
  }
  return exercises;
});
