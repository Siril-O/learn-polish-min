export const wikibooksExerciseTranslations = { pl: {} };
export const wikibooksExercises = wikibooksContexts.flatMap(
  ([sourceKey, topic, slug, prompt, options, sentence, ukrainian, rulePl, ruleUk]) => {
    const familyId = `wikibooks-${topic}-${slug}`;
    return ['choice', 'write', 'sentence'].map((level) => {
      const id = `${familyId}-${level}`;
      wikibooksExerciseTranslations.pl[id] = {
        ...(level === 'sentence' ? { hint: prompt } : { prompt }),
        explanation: `${sentence} ${rulePl}`,
      };
      return {
        id,
        familyId,
        topic,
        level,
        prompt: level === 'sentence' ? ukrainian : prompt,
        answers: [level === 'sentence' ? sentence : options[0]],
        ...(level === 'choice' ? { options: [...options] } : {}),
        ...(level === 'sentence' ? { hint: prompt } : {}),
        explanation: `${sentence} ${ruleUk}`,
        attribution: wikibooksSources[sourceKey],
      };
    });
  },
);
