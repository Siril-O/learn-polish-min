export const spellingExerciseTranslations = { pl: {} };
export const spellingExercises = spellingItems.flatMap(
  ([id, group, sentence, gap, answer, distractor, pl, uk]) =>
    ['choice', 'write'].map((level) => {
      const exerciseId = `spelling-${id}-${level}`;
      spellingExerciseTranslations.pl[exerciseId] = {
        prompt: `Wstaw brakującą literę lub dwuznak (${group}): ${gap}`,
        explanation: `${sentence} ${pl}`,
        hint: 'Wpisz tylko brakującą literę lub dwuznak.',
      };
      return {
        id: exerciseId,
        familyId: `spelling-${id}`,
        topic: 'spelling',
        level,
        prompt: `Встав пропущену літеру або сполучення (${group}): ${gap}`,
        hint: 'Введи лише пропущену літеру або сполучення.',
        answers: [answer],
        ...(level === 'choice' ? { options: [answer, distractor] } : {}),
        explanation: `${sentence} ${uk}`,
      };
    }),
);
