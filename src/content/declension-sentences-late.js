for (const [
  slug,
  prompt,
  answer,
  distractors,
  ukrainianSentence,
  question,
  ukrainianReason,
  polishReason,
  alternatives = [],
] of expandedContexts) {
  const familyId = `narzednik-expanded-${slug}`;
  const explanation = `Орудний: ${question} ${answer}. ${ukrainianReason}`;
  const polishExplanation = `Narzędnik: ${question} ${answer}. ${polishReason}`;
  for (const level of ['choice', 'write', 'sentence']) {
    const id = `${familyId}-${level}`;
    exercises.push({
      id,
      familyId,
      topic: 'narzednik',
      level,
      prompt: level === 'sentence' ? ukrainianSentence : prompt,
      answers:
        level === 'sentence' ? [completeSentence(prompt, answer), ...alternatives] : [answer],
      explanation,
      ...(level === 'choice'
        ? { options: [answer, ...distractors, ...additionalChoiceForms[slug]] }
        : {}),
      ...(level === 'sentence' ? { hint: prompt } : {}),
    });
    translations[id] = { explanation: polishExplanation };
  }
}

