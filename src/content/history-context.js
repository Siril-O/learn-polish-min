export const historyContextTranslations = { pl: {} };

export const historyContextExercises = contexts.flatMap(
  ([slug, sourceEntryId, prompt, options, aliases, explanation, evidence]) => {
    const source = history.find((entry) => entry.id === sourceEntryId);
    if (!source?.original.includes(evidence)) {
      throw new Error(`Missing original history context evidence: ${slug}`);
    }
    const [promptUk, explanationUk] = ukrainian[slug];
    const familyId = `history-context-${slug}`;
    return ['choice', 'write'].map((level) => {
      const id = `${familyId}-${level}`;
      historyContextTranslations.pl[id] = { prompt, explanation };
      return {
        id,
        familyId,
        topic: 'history',
        historyTestType: 'context',
        historyCategory: source.category,
        sourceEntryId,
        historyDate:
          {
            'mickiewicz-death-city': '1855',
            'swedish-peace-location': '1660',
            'first-president': '1922',
            'curie-elements': '1898',
            'pan-tadeusz-author': '1834',
          }[slug] ?? source.year,
        originalEvidence: evidence,
        level,
        prompt: promptUk,
        answers: level === 'choice' ? [options[0]] : [...new Set([options[0], ...aliases])],
        ...(level === 'choice' ? { options: [...options] } : {}),
        explanation: explanationUk,
      };
    });
  },
);
